import { build } from 'esbuild';
import { rm, mkdir, copyFile } from 'node:fs/promises';
await rm('dist', { recursive: true, force: true });
await mkdir('dist', { recursive: true });
await build({ entryPoints: ['ui/main.tsx'], bundle: true, outfile: 'dist/app.js', format: 'esm', platform: 'browser', target: 'chrome140', loader: { '.ttf': 'file' } });
await build({ entryPoints: ['node_modules/monaco-editor/esm/vs/editor/editor.worker.js'], bundle: true, outfile: 'dist/editor.worker.js', format: 'iife', platform: 'browser', target: 'chrome140' });
await build({ entryPoints: ['ui/formatter.worker.ts'], bundle: true, outfile: 'dist/formatter.worker.js', format: 'iife', platform: 'browser', target: 'chrome140' });
await build({ entryPoints: ['ui/python-formatter.worker.ts'], bundle: true, outfile: 'dist/python-formatter.worker.js', format: 'iife', platform: 'browser', target: 'chrome140', loader: { '.wasm': 'binary' } });
await mkdir('dist/licenses/ruff', { recursive: true });
for (const file of ['LICENSE', 'README.md']) await copyFile(`node_modules/@astral-sh/ruff-wasm-web/${file}`, `dist/licenses/ruff/${file}`);
await mkdir('dist/licenses/prettier', { recursive: true });
for (const file of ['LICENSE', 'THIRD-PARTY-NOTICES.md']) await copyFile(`node_modules/prettier/${file}`, `dist/licenses/prettier/${file}`);
await copyFile('ui/index.html', 'dist/index.html');
await copyFile('branding/assets/icons/icon-512.png', 'dist/icon.png');

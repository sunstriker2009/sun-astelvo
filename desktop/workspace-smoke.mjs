    assert.equal(folderDeleted.schemaVersion, 3);
    assert.equal(folderDeleted.deletedFolderTrees[0].folders.length, 3);
    assert.equal(folderDeleted.scripts.some(s => s.id === copiedScript.id), true, 'Unrelated restored script remains active');
    const folderTree = folderDeleted.deletedFolderTrees[0];
    assert.deepEqual(await readFile(path.join(root, `workspace.v2.${createHash('sha256').update(beforeFolderDelete).digest('hex')}.json`)), beforeFolderDelete);
